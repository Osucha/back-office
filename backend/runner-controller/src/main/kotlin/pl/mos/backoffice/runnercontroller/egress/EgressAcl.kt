package pl.mos.backoffice.runnercontroller.egress

/**
 * Smokescreen hostname ACL (https://github.com/stripe/smokescreen, "Hostname ACLs", format `version: v1`).
 * One service (= role) per job, `action: enforce`, `allowed_domains` = the job's resolved egress hosts.
 * The default rule enforces an empty list: anonymous or unknown clients reach nothing.
 */
data class AclService(val name: String, val project: String, val allowedDomains: List<String>)

object EgressAcl {

    /** ACL of a shared per-pool proxy: one role per active job, default deny-all. */
    fun forPool(pool: String, jobs: List<AclService>): Map<String, Any> = mapOf(
        "version" to "v1",
        "services" to jobs.sortedBy { it.name }.map { it.toMap() },
        "default" to mapOf("name" to "default", "project" to pool, "action" to "enforce", "allowed_domains" to emptyList<String>()),
    )

    /**
     * ACL of a dedicated per-job proxy (Docker backend): the job's rule is also the default rule, so the
     * sandbox needs no proxy credentials.
     */
    fun forSingleJob(job: AclService): Map<String, Any> = mapOf(
        "version" to "v1",
        "services" to listOf(job.toMap()),
        "default" to job.toMap() + ("name" to "default"),
    )

    /** YAML rendering (all scalars JSON-quoted, which is valid YAML) for files mounted into the proxy. */
    fun toYaml(acl: Map<String, Any>): String = buildString {
        appendLine("# generated by back-office runner-controller; do not edit")
        appendLine("version: ${quote(acl["version"].toString())}")
        appendLine("services:")
        @Suppress("UNCHECKED_CAST")
        val services = acl["services"] as List<Map<String, Any>>
        if (services.isEmpty()) {
            setLength(length - 1)
            appendLine(" []")
        }
        services.forEach { appendRule(this, it, "  - ", "    ") }
        appendLine("default:")
        @Suppress("UNCHECKED_CAST")
        appendRule(this, acl["default"] as Map<String, Any>, "  ", "  ")
    }

    private fun appendRule(sb: StringBuilder, rule: Map<String, Any>, first: String, rest: String) {
        sb.appendLine("${first}name: ${quote(rule["name"].toString())}")
        sb.appendLine("${rest}project: ${quote(rule["project"].toString())}")
        sb.appendLine("${rest}action: ${quote(rule["action"].toString())}")
        @Suppress("UNCHECKED_CAST")
        val domains = rule["allowed_domains"] as List<String>
        if (domains.isEmpty()) {
            sb.appendLine("${rest}allowed_domains: []")
        } else {
            sb.appendLine("${rest}allowed_domains:")
            domains.forEach { sb.appendLine("$rest  - ${quote(it)}") }
        }
    }

    private fun quote(s: String): String = buildString {
        append('"')
        s.forEach { c ->
            when (c) {
                '"' -> append("\\\"")
                '\\' -> append("\\\\")
                else -> if (c < ' ') append("\\u%04x".format(c.code)) else append(c)
            }
        }
        append('"')
    }

    private fun AclService.toMap(): Map<String, Any> =
        mapOf("name" to name, "project" to project, "action" to "enforce", "allowed_domains" to allowedDomains.distinct())
}
