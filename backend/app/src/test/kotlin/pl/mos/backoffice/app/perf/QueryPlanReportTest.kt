package pl.mos.backoffice.app.perf

import org.flywaydb.core.Flyway
import org.junit.jupiter.api.Tag
import org.junit.jupiter.api.Test
import org.testcontainers.containers.PostgreSQLContainer
import tools.jackson.databind.JsonNode
import tools.jackson.databind.json.JsonMapper
import java.io.File
import java.sql.Connection
import java.sql.DriverManager

/**
 * Index and query review (docs/architecture/performance.md): seeds [PerfDataGenerator] data into a fresh
 * PostgreSQL, runs `EXPLAIN (ANALYZE, BUFFERS)` for the hot queries of the UI and API, once with the
 * indexes added by the review migrations dropped (inside a rolled-back transaction) and once with them,
 * and writes a Markdown report to `app/build/perf/query-plans.md`.
 *
 * Not part of `check`: `./gradlew :app:perfTest` (optional `-Dperf.runs=… -Dperf.usage=… -Dperf.audit=…`,
 * `-Dperf.jdbcUrl=… -Dperf.user=… -Dperf.password=…` to seed an existing database instead, see perf/README.md).
 */
@Tag("perf")
class QueryPlanReportTest {

    private val json = JsonMapper.builder().build()

    /** Migrations of the index review; their `CREATE INDEX` names are dropped for the "before" measurement. */
    private val reviewMigrations = listOf("db/migration/V104__query_review_indexes.sql", "db/migration/V2__usage_query_indexes.sql", "db/migration/V405__audit_query_indexes.sql")

    private val generator = PerfDataGenerator(
        projects = Integer.getInteger("perf.projects", 50),
        runs = Integer.getInteger("perf.runs", 200_000),
        usageRows = Integer.getInteger("perf.usage", 2_000_000),
        auditRows = Integer.getInteger("perf.audit", 1_000_000),
    )

    @Test
    fun `seed and explain the hot queries`() {
        val external = System.getProperty("perf.jdbcUrl")
        if (external != null) {
            run(external, System.getProperty("perf.user", "backoffice"), System.getProperty("perf.password", "backoffice"))
            return
        }
        PostgreSQLContainer("postgres:17-alpine")
            .withCommand("postgres", "-c", "shared_buffers=256MB", "-c", "work_mem=16MB")
            .withStartupTimeout(java.time.Duration.ofMinutes(5))
            .use { pg ->
                pg.start()
                run(pg.jdbcUrl, pg.username, pg.password)
            }
    }

    /** Migrates (no-op when current), seeds (no-op when seeded), and writes the report unless `-Dperf.seedOnly=true`. */
    private fun run(url: String, user: String, password: String) {
        Flyway.configure().dataSource(url, user, password).locations("classpath:db/migration").outOfOrder(true).load().migrate()
        DriverManager.getConnection(url, user, password).use { c ->
            val seeding = generator.seed(c, ::println)
            if (System.getProperty("perf.seedOnly") == "true") return
            val report = report(c, seeding)
            File("build/perf").mkdirs()
            File("build/perf/query-plans.md").writeText(report)
            println(report)
        }
    }

    data class Measurement(val millis: Double, val plan: String)

    private fun report(c: Connection, seeding: List<PerfDataGenerator.Timing>): String {
        val queries = queries(c)
        val newIndexes = reviewMigrations.flatMap { indexNames(it) }
        // warm-up: load the working set into shared buffers once so both passes run warm
        queries.forEach { (_, sql) -> explain(c, sql) }
        c.autoCommit = false
        newIndexes.forEach { name -> c.createStatement().use { it.execute("DROP INDEX IF EXISTS $name") } }
        val before = queries.associate { (name, sql) -> name to measure(c, sql) }
        c.rollback()
        c.autoCommit = true
        val after = queries.associate { (name, sql) -> name to measure(c, sql) }

        val sizes = listOf("workflow_run", "artifact", "approval_request", "ci_execution", "usage_record", "audit_log").associateWith { table ->
            c.createStatement().use { st -> st.executeQuery("SELECT count(*) FROM $table").use { rs -> rs.next(); rs.getLong(1) } }
        }
        return buildString {
            appendLine("# Query plan review (generated by QueryPlanReportTest)")
            appendLine()
            appendLine("Rows: " + sizes.entries.joinToString(", ") { "${it.key} ${"%,d".format(it.value)}" })
            appendLine()
            appendLine("Seeding: " + seeding.joinToString(", ") { "${it.step} ${it.millis / 1000.0}s" })
            appendLine()
            appendLine("Indexes under review: " + newIndexes.joinToString(", ") { "`$it`" })
            appendLine()
            appendLine("| Query | Before (ms) | Plan before | After (ms) | Plan after |")
            appendLine("|---|---:|---|---:|---|")
            queries.forEach { (name, _) ->
                val b = before.getValue(name)
                val a = after.getValue(name)
                appendLine("| $name | ${"%.2f".format(b.millis)} | ${b.plan} | ${"%.2f".format(a.millis)} | ${a.plan} |")
            }
        }
    }

    /** Median execution time of 5 runs of `EXPLAIN ANALYZE`, plus a compact plan outline. */
    private fun measure(c: Connection, sql: String): Measurement {
        val runs = (1..5).map { explain(c, sql) }
        val times = runs.map { it.first }.sorted()
        return Measurement(times[times.size / 2], runs.last().second)
    }

    private fun explain(c: Connection, sql: String): Pair<Double, String> = c.createStatement().use { st ->
        st.executeQuery("EXPLAIN (ANALYZE, BUFFERS, FORMAT JSON) $sql").use { rs ->
            rs.next()
            val root = json.readTree(rs.getString(1)).get(0)
            root.get("Execution Time").asDouble() to outline(root.get("Plan"))
        }
    }

    /** `Limit > Index Scan idx_x` style outline of the plan (first child path + scan nodes). */
    private fun outline(node: JsonNode, depth: Int = 0): String {
        val type = node.get("Node Type").asString()
        val index = node.get("Index Name")?.asString()
        val relation = node.get("Relation Name")?.asString()
        val label = type + (index?.let { " `$it`" } ?: relation?.let { " $it" } ?: "")
        val children = node.get("Plans")?.toList().orEmpty()
        if (children.isEmpty() || depth > 4) return label
        return label + " > " + children.joinToString(" + ") { outline(it, depth + 1) }
    }

    private fun indexNames(resource: String): List<String> {
        val text = javaClass.classLoader.getResource(resource)?.readText()?.lines()?.filterNot { it.trimStart().startsWith("--") }?.joinToString(" ") ?: return emptyList()
        return Regex("(?i)CREATE\\s+(?:UNIQUE\\s+)?INDEX\\s+(?:CONCURRENTLY\\s+)?(?:IF\\s+NOT\\s+EXISTS\\s+)?(\\w+)").findAll(text).map { it.groupValues[1] }.toList()
    }

    private fun queries(c: Connection): List<Pair<String, String>> {
        val member = generator.memberProjects(c).joinToString(", ") { "'$it'" }
        val bigProject = generator.memberProjects(c).first()
        val runId = c.createStatement().use { st -> st.executeQuery("SELECT id FROM workflow_run WHERE project_id = '$bigProject' ORDER BY created_at DESC LIMIT 1 OFFSET 50").use { rs -> rs.next(); rs.getString(1) } }
        val active = "'PENDING', 'RUNNING', 'WAITING'"
        val usageDay = "to_char(date_trunc('day', occurred_at AT TIME ZONE 'UTC'), 'YYYY-MM-DD')"
        val usageSums = "SUM(cost), SUM(input_tokens), SUM(output_tokens), SUM(cache_read_tokens), SUM(cache_write_tokens), COUNT(*)"
        val last30 = "occurred_at >= now() - interval '30 days' AND occurred_at < now()"
        return listOf(
            "runs list, admin (page 1)" to "SELECT * FROM workflow_run ORDER BY created_at DESC LIMIT 20",
            "runs list, admin (count)" to "SELECT count(*) FROM workflow_run",
            "runs list, admin, status=FAILED (page 1)" to "SELECT * FROM workflow_run WHERE status IN ('FAILED') ORDER BY created_at DESC LIMIT 20",
            "runs list, admin, status=FAILED (count)" to "SELECT count(*) FROM workflow_run WHERE status IN ('FAILED')",
