            "runs list, one project (page 5)" to "SELECT * FROM workflow_run WHERE project_id = '$bigProject' ORDER BY created_at DESC LIMIT 20 OFFSET 80",
            "run detail (run + artefacts)" to "SELECT r.*, (SELECT count(*) FROM artifact a WHERE a.run_id = r.id) FROM workflow_run r WHERE r.id = '$runId'",
            "approvals inbox, admin" to "SELECT * FROM approval_request WHERE status = 'OPEN' ORDER BY created_at DESC LIMIT 50",
            "approvals inbox, member" to "SELECT * FROM approval_request WHERE project_id IN ($member) AND status = 'OPEN' ORDER BY created_at DESC LIMIT 50",
            "approval of a run" to "SELECT * FROM approval_request WHERE run_id = '$runId' AND status = 'OPEN' LIMIT 1",
            "CI executions, admin (page 1)" to "SELECT * FROM ci_execution ORDER BY created_at DESC LIMIT 20",
            "CI executions, admin (count)" to "SELECT count(*) FROM ci_execution",
            "CI executions, one project (page 1)" to "SELECT * FROM ci_execution WHERE project_id = '$bigProject' ORDER BY created_at DESC LIMIT 20",
            "CI executions, member (page 1)" to "SELECT * FROM ci_execution WHERE project_id IN ($member) ORDER BY created_at DESC LIMIT 20",
            "CI idempotency lookup" to "SELECT * FROM ci_execution WHERE idempotency_key = 'perf:$runId' AND created_at > now() - interval '1 day' ORDER BY created_at DESC LIMIT 1",
            "usage summary by DAY, 30 days" to "SELECT $usageDay AS grp, $usageSums FROM usage_record WHERE $last30 GROUP BY grp ORDER BY grp ASC",
            "usage summary by MODEL, 30 days" to "SELECT model_label AS grp, $usageSums FROM usage_record WHERE $last30 GROUP BY grp ORDER BY SUM(cost) DESC, grp ASC",
            "usage summary by MODEL, 1 project, 30 days" to "SELECT model_label AS grp, $usageSums FROM usage_record WHERE $last30 AND project_id = '$bigProject' GROUP BY grp ORDER BY SUM(cost) DESC, grp ASC",
            "usage summary by DAY, 365 days" to "SELECT $usageDay AS grp, $usageSums FROM usage_record WHERE occurred_at >= now() - interval '365 days' GROUP BY grp ORDER BY grp ASC",
            "usage total cost this month" to "SELECT coalesce(sum(cost), 0) FROM usage_record WHERE occurred_at >= date_trunc('month', now()) AND occurred_at < now()",
            "usage entries of a project (page 1)" to "SELECT * FROM usage_record WHERE project_id = '$bigProject' ORDER BY occurred_at DESC LIMIT 50",
            "audit search, no filter" to "SELECT * FROM audit_log ORDER BY event_time DESC, id DESC LIMIT 51",
            "audit search, next page (keyset)" to "SELECT * FROM audit_log WHERE (event_time, id) < (now() - interval '100 days', '00000000-0000-0000-0000-000000000000') ORDER BY event_time DESC, id DESC LIMIT 51",
            "audit search, operation" to "SELECT * FROM audit_log WHERE operation = 'approval.decide' ORDER BY event_time DESC, id DESC LIMIT 51",
            "audit search, actor" to "SELECT * FROM audit_log WHERE actor_id = md5('perf-user-7')::uuid ORDER BY event_time DESC, id DESC LIMIT 51",
