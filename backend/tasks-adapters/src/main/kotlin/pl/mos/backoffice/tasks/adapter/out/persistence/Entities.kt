package pl.mos.backoffice.tasks.adapter.out.persistence

import jakarta.persistence.Column
import jakarta.persistence.Entity
import jakarta.persistence.EnumType
import jakarta.persistence.Enumerated
import jakarta.persistence.Id
import jakarta.persistence.Table
import org.hibernate.annotations.JdbcTypeCode
import org.hibernate.type.SqlTypes
import pl.mos.backoffice.shared.tasks.TaskExecutor
import pl.mos.backoffice.tasks.domain.model.PromptMode
import java.time.Instant
import java.util.UUID

/*
 * JPA rows of V300__task_library.sql. JSONB columns are kept as JSON strings and (de)serialised by
 * TaskMappers with Jackson. All fields have defaults for the no-arg constructor generated by kotlin-jpa.
 */

/** Discriminator of the `scope_type` column; `PROJECT` rows carry `project_id`. */
enum class ScopeType { GLOBAL, PROJECT }

@Entity
@Table(name = "task_interface")
class TaskInterfaceEntity(
    @Id val id: UUID = UUID.randomUUID(),
    @Column(nullable = false, length = 64) val key: String = "",
    @Column(nullable = false, length = 200) val name: String = "",
    @Column(nullable = false, columnDefinition = "text") val description: String = "",
    @JdbcTypeCode(SqlTypes.JSON) @Column(nullable = false) val inputs: String = "[]",
    @JdbcTypeCode(SqlTypes.JSON) @Column(nullable = false) val outputs: String = "[]",
    @JdbcTypeCode(SqlTypes.JSON) @Column(nullable = false) val ports: String = "[]",
    @Column(name = "built_in", nullable = false) val builtIn: Boolean = false,
    @Column(name = "created_at", nullable = false) val createdAt: Instant = Instant.EPOCH,
    @Column(name = "updated_at", nullable = false) val updatedAt: Instant = Instant.EPOCH,
    @Column(name = "updated_by_kind", length = 16) val updatedByKind: String? = null,
    @Column(name = "updated_by_id") val updatedById: UUID? = null,
    @Column(name = "updated_by_name", length = 200) val updatedByName: String? = null,
)

@Entity
@Table(name = "task_template")
class TaskTemplateEntity(
    @Id val id: UUID = UUID.randomUUID(),
    @Column(nullable = false, length = 64) val key: String = "",
    @Column(nullable = false, length = 200) val name: String = "",
    @Column(nullable = false, columnDefinition = "text") val description: String = "",
    @Column(nullable = false) val abstract: Boolean = false,
    @Column(name = "extends_key", length = 64) val extendsKey: String? = null,
    @JdbcTypeCode(SqlTypes.JSON) @Column(nullable = false) val implements: String = "[]",
    @Enumerated(EnumType.STRING) @Column(length = 32) val executor: TaskExecutor? = null,
    @Enumerated(EnumType.STRING) @Column(name = "scope_type", nullable = false, length = 16) val scopeType: ScopeType = ScopeType.GLOBAL,
    @Column(name = "project_id") val projectId: UUID? = null,
    @Column(name = "model_profile_id") val modelProfileId: UUID? = null,
    @Column(name = "prompt_system", columnDefinition = "text") val promptSystem: String? = null,
    @Column(name = "prompt_user", columnDefinition = "text") val promptUser: String? = null,
    @Enumerated(EnumType.STRING) @Column(name = "prompt_mode", nullable = false, length = 16) val promptMode: PromptMode = PromptMode.APPEND,
    @JdbcTypeCode(SqlTypes.JSON) @Column(nullable = false) val skills: String = "[]",
    @JdbcTypeCode(SqlTypes.JSON) @Column(name = "remove_skills", nullable = false) val removeSkills: String = "[]",
    @JdbcTypeCode(SqlTypes.JSON) @Column(nullable = false) val config: String = "{}",
    @Column(name = "output_schema", columnDefinition = "text") val outputSchema: String? = null,
    @Column(name = "confidence_field", length = 200) val confidenceField: String? = null,
    @JdbcTypeCode(SqlTypes.JSON) @Column(nullable = false) val produces: String = "[]",
    @JdbcTypeCode(SqlTypes.JSON) @Column(nullable = false) val consumes: String = "[]",
    @JdbcTypeCode(SqlTypes.JSON) @Column(nullable = false) val tags: String = "[]",
    @Column(name = "built_in", nullable = false) val builtIn: Boolean = false,
    @Column(nullable = false) val version: Int = 1,
    @Column(name = "created_at", nullable = false) val createdAt: Instant = Instant.EPOCH,
    @Column(name = "updated_at", nullable = false) val updatedAt: Instant = Instant.EPOCH,
    @Column(name = "updated_by_kind", length = 16) val updatedByKind: String? = null,
    @Column(name = "updated_by_id") val updatedById: UUID? = null,
    @Column(name = "updated_by_name", length = 200) val updatedByName: String? = null,
)

@Entity
@Table(name = "skill")
class SkillEntity(
    @Id val id: UUID = UUID.randomUUID(),
    @Column(nullable = false, length = 64) val key: String = "",
    @Column(nullable = false, length = 200) val name: String = "",
    @Column(nullable = false, columnDefinition = "text") val description: String = "",
    @Column(nullable = false, columnDefinition = "text") val content: String = "",
    @Enumerated(EnumType.STRING) @Column(name = "scope_type", nullable = false, length = 16) val scopeType: ScopeType = ScopeType.GLOBAL,
    @Column(name = "project_id") val projectId: UUID? = null,
    @JdbcTypeCode(SqlTypes.JSON) @Column(nullable = false) val tags: String = "[]",
    @Column(name = "built_in", nullable = false) val builtIn: Boolean = false,
    @Column(name = "created_at", nullable = false) val createdAt: Instant = Instant.EPOCH,
    @Column(name = "updated_at", nullable = false) val updatedAt: Instant = Instant.EPOCH,
    @Column(name = "updated_by_kind", length = 16) val updatedByKind: String? = null,
    @Column(name = "updated_by_id") val updatedById: UUID? = null,
    @Column(name = "updated_by_name", length = 200) val updatedByName: String? = null,
)
