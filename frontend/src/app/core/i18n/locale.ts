/**
 * The UI language (ADR 0026, docs/guides/frontend-development.md "Internationalisation").
 *
 * One build serves every language: `main.ts` resolves the locale before Angular starts, loads the
 * translations with `loadTranslations()` (runtime `$localize`) and only then imports the app.
 * Switching the language writes `bo.locale` and reloads the page, because translated templates
 * and module-level `$localize` constants are evaluated once.
 *
 * This file is part of the initial bundle (main.ts imports it): keep it tiny and free of Angular.
 */

/** Languages the UI is translated into; the first is the source language of the templates. */
export const SUPPORTED_LOCALES = ['en', 'pl'] as const;
export type AppLocale = (typeof SUPPORTED_LOCALES)[number];

/** localStorage key of the user's explicit choice. */
export const LOCALE_STORAGE_KEY = 'bo.locale';

/** The language names shown in the switch: always in their own language. */
export const LOCALE_NAMES: Record<AppLocale, string> = { en: 'English', pl: 'Polski' };

/** Angular `LOCALE_ID` per UI language (English keeps Angular's default en-US formats). */
export const ANGULAR_LOCALE_ID: Record<AppLocale, string> = { en: 'en-US', pl: 'pl' };

export function isAppLocale(value: unknown): value is AppLocale {
  return typeof value === 'string' && (SUPPORTED_LOCALES as readonly string[]).includes(value);
}

/**
 * The stored choice when there is one, else Polish for a Polish browser, else English.
 * `stored` is the raw localStorage value (null when unset or unavailable).
 */
export function resolveLocale(
  stored: string | null | undefined,
  browserLanguage: string | null | undefined,
): AppLocale {
  if (isAppLocale(stored)) return stored;
  return (browserLanguage ?? '').toLowerCase().startsWith('pl') ? 'pl' : 'en';
}

/** The stored choice, or null (private mode, blocked storage, nothing chosen). */
export function readStoredLocale(
  storage: Pick<Storage, 'getItem'> | null = safeStorage(),
): string | null {
  try {
    return storage?.getItem(LOCALE_STORAGE_KEY) ?? null;
  } catch {
    return null;
  }
}

/** URL of the merged translation file of a language (generated by scripts/i18n-merge.mjs). */
export function translationsUrl(locale: AppLocale): string {
  return `/i18n/messages.${locale}.json`;
}

let active: AppLocale = 'en';

/** Set once by main.ts before the app is imported. */
export function setActiveLocale(locale: AppLocale): void {
  active = locale;
}

/**
 * The language the UI runs in. For code outside DI (pure helpers, `Intl` formatters); components
 * may inject `LOCALE_ID` instead (it is `ANGULAR_LOCALE_ID[activeLocale()]`).
 */
export function activeLocale(): AppLocale {
  return active;
}

/** BCP 47 tag for `Intl.*` formatters of the active language. */
export function intlLocale(): string {
  return ANGULAR_LOCALE_ID[active];
}

/**
 * Stores the choice and reloads the page so every template and constant is evaluated in the new
 * language. `reload` is injectable for tests.
 */
export function switchLocale(
  locale: AppLocale,
  reload: () => void = () => globalThis.location?.reload(),
  storage: Pick<Storage, 'setItem'> | null = safeStorage(),
): void {
  try {
    storage?.setItem(LOCALE_STORAGE_KEY, locale);
  } catch {
    // storage unavailable: the browser language decides next time
  }
  if (locale !== active) reload();
}

function safeStorage(): Storage | null {
  try {
    return globalThis.localStorage ?? null;
  } catch {
    return null;
  }
}
